import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

// the release key lives only on the owner's computer (~/.tilfazi), never in the repository; without it a release
// build is signed with the debug key, and cannot update an installed release
val signing = Properties().apply {
    val f = File(System.getProperty("user.home"), ".tilfazi/signing.properties")
    if (f.isFile) f.inputStream().use { load(it) }
}

android {
    namespace = "app.tilfazi.tv"
    compileSdk = 34

    defaultConfig {
        applicationId = "app.tilfazi.tv"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "1.0.0"
    }

    signingConfigs {
        if (signing.isNotEmpty()) create("release") {
            storeFile = File(signing.getProperty("storeFile"))
            storePassword = signing.getProperty("storePassword")
            keyAlias = signing.getProperty("keyAlias")
            keyPassword = signing.getProperty("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures { compose = true }
}

